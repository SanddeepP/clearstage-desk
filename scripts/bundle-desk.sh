#!/usr/bin/env bash
# Bundles the Desk Edge Function into one file (for the Supabase dashboard editor). Needs esbuild (npx downloads it).
set -euo pipefail
cd "$(dirname "$0")/.."
npx --yes esbuild@0.24.0 supabase/functions/desk/index.ts --bundle --format=esm --platform=neutral --external:'npm:*' --target=es2022 --outfile=build/.desk.tmp.ts --log-level=warning
{ echo "// @ts-nocheck"; echo "// GENERATED by scripts/bundle-desk.sh from supabase/functions/desk/index.ts — do not edit. Paste into the Supabase dashboard editor if the CLI isn't available."; cat build/.desk.tmp.ts; } > build/desk.bundle.ts
rm build/.desk.tmp.ts
